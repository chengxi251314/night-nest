def get_character_profile(character_id: str) -> dict | None:
    return CHARACTER_PROFILES.get(character_id)


def build_system_prompt(
    character_id: str,
    relationship_stage: str,
    memories: list[str],
    history_summary: str = ""
) -> str:
    profile = get_character_profile(character_id)
    if not profile:
        return "你是一个AI角色。请用中文回复，2-4句话。保持角色性格一致。"

    # Build stage hint
    stages = profile.get("stages", {})
    stage_hint = stages.get(relationship_stage, "保持角色性格一致地回应。")
    if not stage_hint and relationship_stage:
        # Fuzzy match
        for key, val in stages.items():
            if key in relationship_stage or relationship_stage in key:
                stage_hint = val
                break
        if not stage_hint:
            stage_hint = "保持角色性格一致地回应。"

    memory_text = "\n".join("- " + m for m in memories) if memories else "（暂无关键记忆）"
    history_text = history_summary if history_summary else "（暂无对话历史）"

    return profile["system_prompt"].format(
        stage_hint=stage_hint,
        memories=memory_text,
        history_summary=history_text
    )
